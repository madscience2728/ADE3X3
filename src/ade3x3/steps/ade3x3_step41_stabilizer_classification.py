    print(f"  2744 CXXC orbits ✓")

    print("  Classifying CXXC stabilizers...")
    cxxc_stats = Counter()
    for orb in cxxc_orbits:
        info = classify_subgroup(orb['stabilizer_ids'])
        cxxc_stats[info['stabilizer_type']] += 1
        all_rows.append({
            'schema': 'CXXC',
            'orbit_id': orb['orbit_id'],
            'rep_config_id': orb['rep_config_id'],
            'orbit_size': orb['orbit_size'],
            'stabilizer_order': orb['stabilizer_size'],
            'stabilizer_type': info['stabilizer_type'],
            'is_abelian': info['is_abelian'],
            'element_orders': json.dumps(info['element_orders']),
            'generator_action_ids': json.dumps(info['generator_action_ids']),
        })
    print(f"  CXXC type distribution: {dict(cxxc_stats)}")
