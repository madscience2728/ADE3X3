def write_csv(all_rows: list[dict], path: Path):
    with open(path, 'w', newline='', encoding='utf-8') as f:
        w = csv.DictWriter(f, fieldnames=FIELDS)
        w.writeheader()
        w.writerows(all_rows)
    print(f"  Wrote {len(all_rows)} rows → {path}")


def write_markdown(all_rows: list[dict], stats: dict, path: Path):
    ts = datetime.now().strftime('%Y-%m-%d %H:%M:%S')
    lines = [
        "# Stabilizer Subgroup Classification: CXC and CXXC",
        "",
        f"Generated: {ts}",
        "",
        "[EXACT_DERIVED]",
        "",
        "## Background",
        "",
        "The ambient group is S3×S3×S3 (order 216). Elements have orders in {1,2,3,6}.",
        "For a given orbit with representative `r`, the stabilizer is:",
        "  Stab(r) = {g ∈ G : g·r = r}",
        "which is a subgroup of G by the orbit-stabilizer theorem.",
        "",
        "Isomorphism types are determined by:",
        "  - Subgroup order (= 216 / orbit_size)",
        "  - Element order histogram",
        "  - Abelian vs non-abelian",
        "",
        "**Constraint:** S3×S3×S3 has no elements of order 4, 5, 7, 8, ... (only 1,2,3,6).",
        "This rules out Z4, Q8, D4, Z8, etc. as stabilizer types.",
        "",
    ]

    for schema in ['CXC', 'CXXC']:
        schema_rows = [r for r in all_rows if r['schema'] == schema]
        n = len(schema_rows)
        type_counts = Counter(r['stabilizer_type'] for r in schema_rows)
        order_counts = Counter(r['stabilizer_order'] for r in schema_rows)

        lines += [
            f"## {schema} Stabilizer Classification",
            "",
            f"**Orbit count:** {n}",
            "",
            "### Stabilizer Type Distribution",
            "",
            "| Stabilizer Type | Orbit Count | Fraction |",
            "|-----------------|-------------|----------|",
        ]
        for stype in sorted(type_counts.keys(), key=lambda t: (
            int(next(r['stabilizer_order'] for r in schema_rows if r['stabilizer_type']==t)), t
        )):
            cnt = type_counts[stype]
            lines.append(f"| {stype} | {cnt} | {cnt/n:.4f} |")

        lines += [
            "",
            "### Stabilizer Order Distribution",
            "",
            "| Stabilizer Order | Orbit Count | Orbit Size | Fraction of Orbits |",
            "|------------------|-------------|------------|---------------------|",
        ]
        for order in sorted(order_counts.keys()):
            cnt = order_counts[order]
            orb_size = 216 // order
            lines.append(f"| {order} | {cnt} | {orb_size} | {cnt/n:.4f} |")

        lines += [
            "",
            "### Full Table",
            "",
            "| orbit_id | rep_config_id | orbit_size | stab_order | type | is_abelian | element_orders |",
            "|----------|--------------|------------|------------|------|------------|----------------|",
        ]
        for row in schema_rows:
            lines.append(
                f"| {row['orbit_id']} | {row['rep_config_id']} | {row['orbit_size']} "
                f"| {row['stabilizer_order']} | {row['stabilizer_type']} "
                f"| {row['is_abelian']} | {row['element_orders']} |"
            )

    lines += ["", "---", "*Generated by ade3x3_step41_stabilizer_classification.py*", ""]
    with open(path, 'w', encoding='utf-8') as f:
        f.write("\n".join(lines))
    print(f"  Wrote markdown → {path}")

