"""
ade3x3_step41_stabilizer_classification.py

Stabilizer Subgroup Classification for CXC (50 orbits) and CXXC (2744 orbits).

For each orbit, classify the stabilizer subgroup by:
  1. Order (= 216 / orbit_size, already known)
  2. Element orders (lcm of component permutation orders in S3×S3×S3)
  3. Abelian check (pairwise commutativity)
  4. Isomorphism type (human-readable name)

Structural constraint: elements of S3×S3×S3 have orders in {1,2,3,6}.
Therefore stabilizer subgroups in CXXC (sizes {1,2,4,8}) are:
  - Order 1: Trivial
  - Order 2: Z2
  - Order 4: Z2xZ2 (no order-4 elements possible)
  - Order 8: (Z2)^3  (no order-4/8 elements possible; abelian group of exponent 2)

CXC orbits have sizes dividing 216; we classify whatever appears.

Output columns:
  schema | orbit_id | rep_config_id | orbit_size | stabilizer_order
  | stabilizer_type | is_abelian | element_orders | generator_action_ids

Provenance: [EXACT_DERIVED]
"""

